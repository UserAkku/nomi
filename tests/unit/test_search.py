def test_build_chunks_sample_repo(sample_repo):
    index = CodeIndex.build(sample_repo)
    paths = {c.path for c in index.chunks}
    assert "src/widget/parser.py" in paths
    kinds = {c.path: c.kind for c in index.chunks}
    assert kinds["tests/test_parser.py"] == "test"
    assert kinds["README.md"] == "doc"
    assert kinds["src/widget/net.py"] == "code"
    assert index.files_indexed == len(sample_repo.files)
    assert not index.truncated
    parser = next(c for c in index.chunks if c.path == "src/widget/parser.py")
    lines = sample_repo.lines("src/widget/parser.py")
    assert parser.start == 1 and parser.end == len(lines)
    assert parser.text.split("\n") == lines


def test_chunk_overlap_and_line_numbers(make_repo):
    ws = make_repo({"big.py": "".join(f"line_{i} = {i}\n" for i in range(1, 101))})
    index = CodeIndex.build(ws, chunk_lines=40, overlap=10)
    spans = [(c.start, c.end) for c in index.chunks]
    assert spans == [(1, 40), (31, 70), (61, 100)]
    for chunk in index.chunks:
        assert chunk.text.split("\n")[0] == f"line_{chunk.start} = {chunk.start}"
        assert chunk.text.split("\n")[-1] == f"line_{chunk.end} = {chunk.end}"


def test_degenerate_chunk_parameters(make_repo):
    ws = make_repo({"a.py": "alpha = 1\nbeta = 2\ngamma = 3\n"})
    index = CodeIndex.build(ws, chunk_lines=0, overlap=50)
    assert [(c.start, c.end) for c in index.chunks] == [(1, 1), (2, 2), (3, 3)]


def test_crlf_and_blank_files(make_repo):
    ws = make_repo({"win.py": "first = 1\r\nsecond_value = 2\r\n", "blank.py": "\n\n   \n"})
    index = CodeIndex.build(ws)
    assert [c.path for c in index.chunks] == ["win.py"]
    assert "\r" not in index.chunks[0].text
    (hit, _score), *_ = index.search("second_value")
    assert (hit.start, hit.end) == (1, 2)


