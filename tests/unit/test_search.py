# ------------------------------------------------------------------ tokenize


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("parse_url", ["parse_url", "parse", "url"]),
        ("fetchUser", ["fetchuser", "fetch", "user"]),
        ("HTTPServer", ["httpserver", "http", "server"]),
        ("parseURL", ["parseurl", "parse", "url"]),
        ("getV2Data", ["getv2data", "get", "v2", "data"]),
        ("__init__", ["init"]),
        ("Client", ["client"]),
        ("url", ["url"]),
        ("a-b c", []),  # single characters dropped
        ("the self and return", []),  # stopwords dropped
        ("timeout=10", ["timeout", "10"]),
        ("", []),
    ],
)
def test_tokenize(text, expected):
    assert tokenize(text) == expected


def test_tokenize_unicode_and_punctuation():
    assert tokenize("naïve_café → größe!") == ["naïve_café", "naïve", "café", "größe"]
    assert tokenize("raise ValueError('empty url')") == [
        "raise",
        "valueerror",
        "value",
        "error",
        "empty",
        "url",
    ]


def test_tokenize_drops_huge_tokens_and_handles_huge_input():
    assert tokenize("x" * 500) == []
    assert len(tokenize("alpha beta " * 50_000)) == 100_000


