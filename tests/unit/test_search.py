def test_finds_parser_for_empty_url_claim(sample_repo):
    index = CodeIndex.build(sample_repo)
    results = index.search("parse_url raises ValueError on empty url input")
    assert results[0][0].path == "src/widget/parser.py"
    scores = [s for _, s in results]
    assert scores == sorted(scores, reverse=True)
    assert all(s > 0 for s in scores)


def test_bm25_rare_terms_and_length_normalization():
    filler = "\n".join(f"common_word value_{i}" for i in range(30))
    index = CodeIndex(
        [
            Chunk("a.py", 1, 1, "common_word rare_token", "code"),
            Chunk("b.py", 1, 1, "common_word common_word", "code"),
            Chunk("c.py", 1, 31, "rare_token\n" + filler, "code"),
        ]
    )
    ranked = [c.path for c, _ in index.search("common_word rare_token")]
    assert ranked[0] == "a.py"  # has both terms and is short
    assert ranked.index("c.py") < ranked.index("b.py")  # the rare term outweighs repetition


def test_per_file_diversity(make_repo):
    hot = "\n".join(f"retry_backoff({i})" for i in range(200))
    ws = make_repo({"hot.py": hot, "cold.py": "retry_backoff(1)\n", "other.py": "unrelated = 1\n"})
    index = CodeIndex.build(ws)
    results = index.search("retry_backoff", k=5)
    paths = [c.path for c, _ in results]
    assert paths.count("hot.py") == 2
    assert "cold.py" in paths
    assert "other.py" not in paths


def test_boost_paths_and_kinds(make_repo):
    body = "def load_config(path):\n    return path\n"
    ws = make_repo({"a/config.py": body, "b/config.py": body, "docs/config.md": "load_config\n"})
    index = CodeIndex.build(ws)
    plain = index.search("load_config", kinds={"code"})
    assert [c.path for c, _ in plain] == ["a/config.py", "b/config.py"]  # tie -> path order
    boosted = index.search("load_config", kinds={"code"}, boost_paths={"./b/config.py"})
    assert boosted[0][0].path == "b/config.py"
    assert boosted[0][1] == pytest.approx(plain[0][1] * 1.5)
    assert [c.kind for c, _ in index.search("load_config", kinds={"doc"})] == ["doc"]
    assert index.search("load_config", kinds=set()) == []


def test_search_is_deterministic(sample_repo):
    a = CodeIndex.build(sample_repo).search("timeout retries url", k=8)
    b = CodeIndex.build(sample_repo).search("timeout retries url", k=8)
    assert a == b


def test_build_is_fast_for_2k_files(tmp_path: Path):
    root = tmp_path / "large"
    for i in range(2000):
        pkg = root / f"pkg{i % 20}"
        pkg.mkdir(parents=True, exist_ok=True)
        lines = [
            f"def handler_{i}_{j}(request, timeout=10):\n    return fetchUser{j}(request)\n"
            for j in range(30)
        ]
        (pkg / f"mod{i}.py").write_text("".join(lines))
    ws = Workspace(root)
    started = time.perf_counter()
    index = CodeIndex.build(ws)
    assert time.perf_counter() - started < 5
    assert index.files_indexed == 2000
    (top, _), *_ = index.search("handler_1234_7 timeout")
    assert top.path == "pkg14/mod1234.py"
